#!/bin/sh
# tests/check-akku-lock.sh: what scripts/check-akku-lock promises, checked
# with a fake akku, so it needs no Akku and no network. `make
# check-site-deps` runs it.
#
# The fake keeps an index of its own, a file under the row's state
# directory: `akku update` replaces it with FAKE_TODAY's file, when there
# is one, as the real one fetches today's index, and `akku lock` writes it
# as the lock it makes. So a row sets the lock akku would make by writing
# the index, or by FAKE_TODAY. Each command it runs is logged.
set -u
cd "$(dirname "$0")/.."
script=$PWD/scripts/check-akku-lock

scratch=$(mktemp -d "${TMPDIR:-/tmp}/check-akku-lock-test.XXXXXX")
trap 'rm -rf "$scratch"' EXIT
fails=0
pass() { echo "PASS: $1"; }
fail() { echo "FAIL: $1" >&2; fails=$((fails + 1)); }

# The fake akku. `update` obeys FAKE_UPDATE: ok; fail, which exits 255,
# as Akku does on an error; and missing, which exits 2 with scripts/akku's
# words for an Akku 1.2.0 that isn't there. `lock` obeys
# FAKE_LOCK: index, the default, writes the index as Akku.lock; fail is an
# akku that finds no solution; unknown, one whose index lacks two of the
# manifest's packages, and warns of each twice, as Akku 1.2.0's lock does.
# Either command fails where it finds no Akku.manifest: it runs in a project.
mkdir -p "$scratch/bin"
cat > "$scratch/bin/akku" <<'EOF'
#!/bin/sh
echo "$*" >> "$FAKE_STATE/log"
[ -f Akku.manifest ] || { echo "fake akku: no Akku.manifest here" >&2; exit 1; }
case ${1:-} in
  update)
    case ${FAKE_UPDATE:-ok} in
      fail) echo "fake akku: could not download the index" >&2; exit 255 ;;
      missing) echo "akku: no Akku 1.2.0 at build/akku-tool/akku/akku-1.2.0.src. Run 'make akku-deps' on the host, where the network is." >&2; exit 2 ;;
    esac
    [ -z "${FAKE_TODAY:-}" ] || cp "$FAKE_TODAY" "$FAKE_STATE/index" ;;
  lock)
    case ${FAKE_LOCK:-index} in
      index) cp "$FAKE_STATE/index" Akku.lock ;;
      fail) echo "fake akku: no solution" >&2; exit 1 ;;
      unknown)
        printf '[warning] Unknown package: "chez-libuv"\n[warning] Unknown package: "chez-uri"\n' >&2
        echo '[info] Solving dependencies...' >&2
        printf '[warning] Unknown package: "chez-libuv"\n[warning] Unknown package: "chez-uri"\n' >&2
        echo '&message: "No acceptable solution - dependency hell"' >&2
        exit 1 ;;
    esac ;;
  *) exit 2 ;;
esac
EOF
chmod +x "$scratch/bin/akku"

# The project: its manifest and its committed lock, in a directory of their
# own, which is also where each run starts.
mkdir -p "$scratch/proj"
echo '(akku-package ("circuit" "0.3.0") (depends ("chez-http-server" "^0.11.0")))' > "$scratch/proj/Akku.manifest"

# lock FILE NAME URL SHA [NAME URL SHA]...: a lock in Akku 1.2.0's layout,
# each sha256 on a line of its own.
lock() {
  out=$1; shift
  { echo '#!r6rs ; -*- mode: scheme; coding: utf-8 -*-'
    echo ';; This file is automatically generated - do not change it by hand.'
    echo '(import (akku format lockfile))'
    echo '(projects'
    while [ "$#" -ge 3 ]; do
      printf '  ((name "%s")\n    (location\n      (url "%s"))\n    (content\n      (sha256\n        "%s")))\n' "$1" "$2" "$3"
      shift 3
    done
    echo ')'; } > "$out"
}

url=https://archive.akkuscm.org/archive/pkg/c/chez-http-server_0.11.0_repack.tar.xz
sha=0fb49d54e71bb2123e4dcf28f737372e2e86d16a7647f8e5cdf86d9784913ba5
other=1fb49d54e71bb2123e4dcf28f737372e2e86d16a7647f8e5cdf86d9784913ba5
url2=https://archive.akkuscm.org/archive/pkg/c/chez-websocket_0.6.0_repack.tar.xz
sha2=5a971860ef021d4bb8e38fd758311380bca7067c6c8134fd15442106fbae510c
lock "$scratch/one.lock" chez-http-server "$url" "$sha"
lock "$scratch/two.lock" chez-http-server "$url" "$sha" chez-websocket "$url2" "$sha2"

# project NAME URL SHA: how the check shows a project of lock's.
project() { printf 'project ((name "%s") (location (url "%s")) (content (sha256 "%s")))' "$1" "$2" "$3"; }

# hooked FILE RUN PHASE: a lock of chez-libuv alone in Akku 1.2.0's layout,
# with the scripts form Akku.lock's chez-libuv entry has: RUN its command's
# string, PHASE the symbol cond-expand tests.
liburl=https://archive.akkuscm.org/archive/pkg/c/chez-libuv_0.11.0_repack.tar.xz
libsha=7959508d59b2554a870cb559f5058f577969e762c991f16bccd42beade5b6693
hooked() {
  { echo '#!r6rs ; -*- mode: scheme; coding: utf-8 -*-'
    echo ';; This file is automatically generated - do not change it by hand.'
    echo '(import (akku format lockfile))'
    echo '(projects'
    printf '  ((name "chez-libuv")\n    (location\n      (url "%s"))\n    (content\n      (sha256\n        "%s"))\n' "$liburl" "$libsha"
    printf '    (scripts\n      (cond-expand\n        ((and %s (or darwin linux))\n          (run "%s"))))))\n' "$3" "$2"
  } > "$1"
}

# run COMMITTED INDEX [VAR=VALUE]...: the script, from the project's
# directory, with COMMITTED as Akku.lock and INDEX as the fake's index,
# with the fake akku unless a VAR names another, and the VARs in its
# environment. Its output is in $scratch/out, its status returned.
run() {
  rm -rf "$scratch/state"; mkdir "$scratch/state"
  cp "$1" "$scratch/proj/Akku.lock"
  cp "$2" "$scratch/state/index"
  shift 2
  (cd "$scratch/proj" &&
   env FAKE_STATE="$scratch/state" AKKU="$scratch/bin/akku" "$@" sh "$script") > "$scratch/out" 2>&1
}

# holds TEXT...: each is in the output.
holds() {
  for want in "$@"; do grep -qF -- "$want" "$scratch/out" || return 1; done
}

# log: the commands the fake ran, one a line, joined by spaces.
log() { tr '\n' ' ' < "$scratch/state/log" 2>/dev/null | sed 's/ $//'; }

# kept COMMITTED: the committed lock is as the row wrote it, and no lock was
# made beside it: akku ran on a copy of the manifest, elsewhere.
kept() { cmp -s "$1" "$scratch/proj/Akku.lock"; }

# 1. The same lock: passes, naming how many projects agree, after akku
#    update, then akku lock.
if run "$scratch/two.lock" "$scratch/two.lock" \
   && holds "check-akku-lock: Akku.lock is akku lock's output for Akku.manifest (2 project(s))" \
   && [ "$(log)" = "update lock" ] && kept "$scratch/two.lock"; then
  pass "a lock akku makes again byte for byte passes, after akku update, then akku lock"
else
  fail "a lock akku makes again byte for byte passes, after akku update, then akku lock (log: $(log))"; cat "$scratch/out" >&2
fi

# 2. The same projects in another layout (every string after its key, one
#    line a project): passes.
printf '(import (akku format lockfile))\n(projects ((name "chez-http-server") (location (url "%s")) (content (sha256 "%s"))))\n' \
  "$url" "$sha" > "$scratch/oneline.lock"
if run "$scratch/one.lock" "$scratch/oneline.lock" && holds "(1 project(s))" && kept "$scratch/one.lock"; then
  pass "a lock that differs only in layout passes"
else
  fail "a lock that differs only in layout passes"; cat "$scratch/out" >&2
fi

# 3. The same projects in another order: passes.
lock "$scratch/swapped.lock" chez-websocket "$url2" "$sha2" chez-http-server "$url" "$sha"
if run "$scratch/two.lock" "$scratch/swapped.lock" && holds "(2 project(s))"; then
  pass "a lock that differs only in the order of its projects passes"
else
  fail "a lock that differs only in the order of its projects passes"; cat "$scratch/out" >&2
fi

# 4. Another sha256: fails, and shows it.
lock "$scratch/sha.lock" chez-http-server "$url" "$other" chez-websocket "$url2" "$sha2"
if ! run "$scratch/two.lock" "$scratch/sha.lock" \
   && holds "check-akku-lock: FAIL: Akku.lock is not what akku lock makes of Akku.manifest: run make lock, and commit it" \
            "> $(project chez-http-server "$url" "$other")" "< $(project chez-http-server "$url" "$sha")" \
   && kept "$scratch/two.lock"; then
  pass "a lock with another sha256 fails, and shows it"
else
  fail "a lock with another sha256 fails, and shows it"; cat "$scratch/out" >&2
fi

# 5. Another URL: fails, and shows it.
lock "$scratch/url.lock" chez-http-server "$url.old" "$sha" chez-websocket "$url2" "$sha2"
if ! run "$scratch/two.lock" "$scratch/url.lock" \
   && holds "check-akku-lock: FAIL: Akku.lock is not what" "> $(project chez-http-server "$url.old" "$sha")"; then
  pass "a lock with another url fails, and shows it"
else
  fail "a lock with another url fails, and shows it"; cat "$scratch/out" >&2
fi

# 6. A project akku's lock has and the committed one lacks: fails, naming it.
if ! run "$scratch/one.lock" "$scratch/two.lock" \
   && holds "check-akku-lock: FAIL: Akku.lock is not what" "> $(project chez-websocket "$url2" "$sha2")"; then
  pass "a project missing from the committed lock fails, and names it"
else
  fail "a project missing from the committed lock fails, and names it"; cat "$scratch/out" >&2
fi

# 7. A project the committed lock has and akku's lacks: fails, naming it.
if ! run "$scratch/two.lock" "$scratch/one.lock" \
   && holds "check-akku-lock: FAIL: Akku.lock is not what" "< $(project chez-websocket "$url2" "$sha2")"; then
  pass "a project missing from akku's lock fails, and names it"
else
  fail "a project missing from akku's lock fails, and names it"; cat "$scratch/out" >&2
fi

# 8. Today's index, not the last run's: akku update moves the index to one
#    with a release the committed lock, made on the old index, lacks. The
#    old index alone would pass.
if ! run "$scratch/one.lock" "$scratch/one.lock" FAKE_TODAY="$scratch/two.lock" \
   && holds "> $(project chez-websocket "$url2" "$sha2")" && [ "$(log)" = "update lock" ]; then
  pass "a release on today's index, which akku update fetches, fails a lock made before it"
else
  fail "a release on today's index, which akku update fetches, fails a lock made before it (log: $(log))"; cat "$scratch/out" >&2
fi

# 9. No akku at the path AKKU names, or on PATH by its name: fails, not
#    skipped, naming make akku-deps, and runs nothing.
if ! run "$scratch/two.lock" "$scratch/two.lock" AKKU="$scratch/bin/no-such-akku" \
   && holds "check-akku-lock: FAIL: no Akku at $scratch/bin/no-such-akku: run make akku-deps, which fetches Akku 1.2.0" \
   && ! holds "skipped" && [ ! -e "$scratch/state/log" ]; then
  pass "with no akku at its path the check fails, naming make akku-deps"
else
  fail "with no akku at its path the check fails, naming make akku-deps"; cat "$scratch/out" >&2
fi
if ! run "$scratch/two.lock" "$scratch/two.lock" AKKU=no-such-akku \
   && holds "check-akku-lock: FAIL: no no-such-akku on PATH: run make akku-deps, which fetches Akku 1.2.0" \
   && ! holds "skipped" && [ ! -e "$scratch/state/log" ]; then
  pass "with no akku on PATH by its name the check fails, naming make akku-deps"
else
  fail "with no akku on PATH by its name the check fails, naming make akku-deps"; cat "$scratch/out" >&2
fi

# 10. AKKU as a path relative to where the check starts, as the Makefile
#     gives it, is that akku, though akku runs elsewhere.
if run "$scratch/two.lock" "$scratch/two.lock" AKKU=../bin/akku \
   && holds "(2 project(s))" && [ "$(log)" = "update lock" ]; then
  pass "an AKKU relative to where the check starts is that akku"
else
  fail "an AKKU relative to where the check starts is that akku (log: $(log))"; cat "$scratch/out" >&2
fi

# 11. akku update fails: so does the check, not skipped, with akku's own
#     words, and no lock is made.
if ! run "$scratch/two.lock" "$scratch/two.lock" FAKE_UPDATE=fail \
   && holds "  fake akku: could not download the index" \
            "check-akku-lock: FAIL: $scratch/bin/akku update could not fetch today's index: it needs the network" \
   && ! holds "skipped" && ! holds "make akku-deps" && [ "$(log)" = "update" ] && kept "$scratch/two.lock"; then
  pass "a failed akku update fails the check, and locks nothing"
else
  fail "a failed akku update fails the check, and locks nothing (log: $(log))"; cat "$scratch/out" >&2
fi

# 11b. akku update exits 2, as scripts/akku does with no Akku 1.2.0 to run:
#      the check fails, not skipped, naming make akku-deps, not the
#      network, and no lock is made.
if ! run "$scratch/two.lock" "$scratch/two.lock" FAKE_UPDATE=missing \
   && holds "  akku: no Akku 1.2.0 at build/akku-tool/akku/akku-1.2.0.src." \
            "check-akku-lock: FAIL: no Akku 1.2.0: run make akku-deps" \
   && ! holds "skipped" && ! holds "it needs the network" && [ "$(log)" = "update" ] && kept "$scratch/two.lock"; then
  pass "an akku update that exits 2, with no Akku 1.2.0 to run, fails naming make akku-deps"
else
  fail "an akku update that exits 2, with no Akku 1.2.0 to run, fails naming make akku-deps (log: $(log))"; cat "$scratch/out" >&2
fi

# 12. akku lock fails: so does the check, with akku's own words.
if ! run "$scratch/two.lock" "$scratch/two.lock" FAKE_LOCK=fail \
   && holds "  fake akku: no solution" "check-akku-lock: FAIL: $scratch/bin/akku lock could not lock Akku.manifest" \
   && ! holds "index does not know"; then
  pass "a failed akku lock fails the check"
else
  fail "a failed akku lock fails the check"; cat "$scratch/out" >&2
fi

# 13. An index that does not know a package, even today's: fails, naming
#     each one.
if ! run "$scratch/two.lock" "$scratch/two.lock" FAKE_LOCK=unknown \
   && holds "check-akku-lock: FAIL: today's index does not know chez-libuv chez-uri: check their names in Akku.manifest"; then
  pass "an index that does not know a package fails, naming it"
else
  fail "an index that does not know a package fails, naming it"; cat "$scratch/out" >&2
fi

# 14. A manifest or a committed lock that isn't there: fails, naming it.
if ! run "$scratch/two.lock" "$scratch/two.lock" AKKU_MANIFEST="$scratch/proj/none.manifest" \
   && holds "check-akku-lock: FAIL: $scratch/proj/none.manifest not found" && [ ! -e "$scratch/state/log" ]; then
  pass "a manifest that isn't there fails, naming it"
else
  fail "a manifest that isn't there fails, naming it"; cat "$scratch/out" >&2
fi
if ! run "$scratch/two.lock" "$scratch/two.lock" AKKU_LOCK="$scratch/proj/none.lock" \
   && holds "check-akku-lock: FAIL: $scratch/proj/none.lock not found" && [ ! -e "$scratch/state/log" ]; then
  pass "a committed lock that isn't there fails, naming it"
else
  fail "a committed lock that isn't there fails, naming it"; cat "$scratch/out" >&2
fi

# 15. Every token counts, symbols and strings alike, in order, but not the
#     layout or the comments. Locks that differ only in chez-libuv's
#     (run "...") string fail, and so do ones that differ only past a ; in
#     it, which is no comment there.
hooked "$scratch/hook.lock" "sh scripts/akku-install" pre-install
hooked "$scratch/hook-run.lock" "sh scripts/other-install" pre-install
if ! run "$scratch/hook.lock" "$scratch/hook-run.lock" \
   && holds "check-akku-lock: FAIL: Akku.lock is not what" \
            '< project ((name "chez-libuv")' '(run "sh scripts/akku-install")))))' \
            '> project ((name "chez-libuv")' '(run "sh scripts/other-install")))))'; then
  pass "locks that differ only in a (run \"...\") string fail, and show it"
else
  fail "locks that differ only in a (run \"...\") string fail, and show it"; cat "$scratch/out" >&2
fi
hooked "$scratch/hook-semi.lock" "sh scripts/akku-install; true" pre-install
hooked "$scratch/hook-semi2.lock" "sh scripts/akku-install; false" pre-install
if ! run "$scratch/hook-semi.lock" "$scratch/hook-semi2.lock" \
   && holds '(run "sh scripts/akku-install; true")))))' '(run "sh scripts/akku-install; false")))))'; then
  pass "locks that differ only past a ; inside a string fail"
else
  fail "locks that differ only past a ; inside a string fail"; cat "$scratch/out" >&2
fi

# 16. Locks that differ only in a symbol: fail, and show it.
hooked "$scratch/hook-post.lock" "sh scripts/akku-install" post-install
if ! run "$scratch/hook.lock" "$scratch/hook-post.lock" \
   && holds "check-akku-lock: FAIL: Akku.lock is not what" \
            '(cond-expand ((and pre-install (or darwin linux))' '(cond-expand ((and post-install (or darwin linux))'; then
  pass "locks that differ only in a symbol fail, and show it"
else
  fail "locks that differ only in a symbol fail, and show it"; cat "$scratch/out" >&2
fi

# 17. The same tokens in another layout, with comments of their own, a ;
#     inside a string among them: agree.
printf '%s\n' '(import (akku format lockfile)) ; the format' \
  "(projects ((name \"chez-libuv\") (location (url \"$liburl\")) ; where it is" \
  "  ;; a comment of a line's own" \
  "     (content (sha256 \"$libsha\")) (scripts (cond-expand ((and pre-install" \
  '  (or darwin linux)) (run "sh scripts/akku-install; true"))))))' > "$scratch/hook-layout.lock"
if run "$scratch/hook-semi.lock" "$scratch/hook-layout.lock" && holds "(1 project(s))"; then
  pass "locks that differ only in layout and comments agree"
else
  fail "locks that differ only in layout and comments agree"; cat "$scratch/out" >&2
fi

if [ "$fails" -eq 0 ]; then
  echo "check-akku-lock: all checks passed"
else
  echo "check-akku-lock: $fails check(s) failed" >&2
  exit 1
fi
